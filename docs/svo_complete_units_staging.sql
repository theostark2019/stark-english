-- This prepares lesson definitions and teacher rubrics; lessons remain DRAFT until preview QA passes.
create table if not exists public.svo_unit_specs(
 episode_id uuid primary key references public.episodes(id) on delete cascade,
 kind text not null check(kind in ('lesson','review')),
 source_page integer not null check(source_page between 10 and 29),
 expected_translations integer not null default 0,
 expected_choices integer not null default 0,
 expected_gaps integer not null default 0,
 expected_dictation integer not null default 0,
 expected_questions integer not null default 0,
 expected_fills integer not null default 0,
 expected_originals integer not null default 2,
 updated_at timestamptz not null default now()
);
alter table public.svo_unit_specs enable row level security;
revoke all on public.svo_unit_specs from anon,authenticated;

